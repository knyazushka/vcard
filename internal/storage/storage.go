// Package storage прячет за интерфейсом место, где лежат файлы.
//
// Сейчас реализация одна — локальный диск, и она делает процесс не stateless:
// вторую реплику с ней поднимать нельзя, половина аватарок окажется не на том
// поде. Это осознанный долг первого этапа. Весь смысл интерфейса в том, чтобы
// переезд на S3 стоил одного нового файла и переменной окружения, а не
// миграции данных с переписыванием колонок.
//
// Отсюда же правило: в базе хранится КЛЮЧ, никогда не URL. Ключ не зависит
// от того, где файлы лежат сегодня.
package storage

import (
	"context"
	"io"
)

// BlobStore — хранилище бинарных объектов: аватарок, логотипов, карточек.
type BlobStore interface {
	// Put кладёт объект по ключу, перезаписывая существующий.
	Put(ctx context.Context, key string, r io.Reader, contentType string) error
	// Get открывает объект на чтение.
	Get(ctx context.Context, key string) (io.ReadCloser, error)
	// Delete удаляет объект; отсутствие объекта ошибкой не считается.
	Delete(ctx context.Context, key string) error
	// URL собирает публичный адрес. Пустой ключ даёт пустую строку —
	// вызывающему не приходится проверять это самому.
	URL(key string) string
}
